int SeedRom_ApplyUSPatches(uint8_t *rom, uint32_t size, int verbose) {
  uint8_t *found[sizeof(kSeedUSPatches) / sizeof(kSeedUSPatches[0])];
  int applied = 0, skipped = 0;
  for (size_t i = 0; i < sizeof(kSeedUSPatches) / sizeof(kSeedUSPatches[0]); i++) {
    const SeedUSPatch *p = &kSeedUSPatches[i];
    const uint8_t *sig = kSeedUSPatchData + p->sig_off;
    uint32_t lo = (p->us_off >> 15) << 15;
    uint32_t hi = lo + 0x8000;
    if (hi > size)
      hi = size;
    found[i] = NULL;
    int hits = 0;
    for (uint32_t off = lo; off + p->sig_len <= hi; off++) {
      if (memcmp(rom + off, sig, p->sig_len) == 0) {
        found[i] = rom + off;
        if (++hits > 1)
          break;
      }
    }
    if (hits != 1) {
      skipped++;
      if (verbose)
        fprintf(stderr, "seed rom: skip US %06X (%d signature hits)\n", p->us_off, hits);
      found[i] = NULL;
    }
  }
  for (size_t i = 0; i < sizeof(kSeedUSPatches) / sizeof(kSeedUSPatches[0]); i++) {
    if (!found[i])
      continue;
    const SeedUSPatch *p = &kSeedUSPatches[i];
    memcpy(found[i] + p->patch_off, kSeedUSPatchData + p->new_off, p->new_len);
    applied++;
  }
  if (verbose)
    fprintf(stderr, "seed rom: %d US signature patches applied, %d skipped\n", applied, skipped);
  return applied;
}

// The US PatchRom relocates BufferAndBuildMap16Stripes_Y to a thunk at
// $02:FF6E and points four call sites at it. JP 1.0 has the same call sites
// but its free space is at a different address, so build the thunk there and
// use the relocated address in the JSR operands.
static uint8_t *FindUniqueInBank(const uint8_t *sig, uint16_t sig_len,
                                 uint8_t *rom, uint32_t bank) {
  uint32_t lo = bank << 15;
  uint32_t hi = lo + 0x8000;
  uint8_t *found = NULL;
  int hits = 0;
  for (uint32_t off = lo; off + sig_len <= hi; off++) {
    if (memcmp(rom + off, sig, sig_len) == 0) {
      found = rom + off;
      if (++hits > 1)
        return NULL;
    }
  }
  return found;
}

int SeedRom_ApplyMap16Stripes(uint8_t *rom, int verbose) {
  static const uint8_t kThunkSig[] = {
    0xc8, 0xe8, 0xd0, 0x05, 0xa2, 0x00, 0x80, 0xe6, 0xca, 0x86, 0xc8, 0x60,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
    0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff, 0xff,
  };
  static const uint8_t kThunk[] = {
    0xc0, 0x00, 0x20, 0x90, 0x03, 0xa9, 0x00, 0x00, 0x9d, 0x00, 0x05, 0x60,
  };
  static const uint8_t kCalls[][35] = {
    { 0x00, 0x20, 0x85, 0x00, 0xa9, 0x7e, 0x00, 0x85, 0x02, 0xa9, 0x10, 0x00,
      0x85, 0x03, 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f,
      0x00, 0xaa, 0x98, 0x18, 0x69, 0x80, 0x00, 0xa8, 0xb7, 0x00, 0x9d },
    { 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f, 0x00, 0xaa, 0x98, 0x18, 0x69, 0x80,
      0x00, 0xa8, 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f,
      0x00, 0xaa, 0x98, 0x18, 0x69, 0x80, 0x00, 0xa8, 0xc6, 0x03, 0xd0 },
    { 0x00, 0x20, 0x85, 0x00, 0xa9, 0x7e, 0x00, 0x85, 0x02, 0xa9, 0x10, 0x00,
      0x85, 0x03, 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f,
      0x00, 0xaa, 0xc8, 0xc8, 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8 },
    { 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f, 0x00, 0xaa,
      0xc8, 0xc8, 0xb7, 0x00, 0x9d, 0x00, 0x05, 0xe8, 0xe8, 0x8a, 0x29, 0x3f,
      0x00, 0xaa, 0xc8, 0xc8, 0xc6, 0x03, 0xd0, 0xe0, 0x64, 0x00, 0xa5 },
  };
  uint8_t *sig = FindUniqueInBank(kThunkSig, sizeof(kThunkSig), rom, 2);
  if (!sig) {
    if (verbose)
      fprintf(stderr, "seed rom: skip map16 stripe thunk (signature not unique)\n");
    return 0;
  }
  uint8_t *thunk = sig + 12;
  uint16_t addr = (uint16_t)(0x8000 + (thunk - (rom + 0x10000)));
  memcpy(thunk, kThunk, sizeof(kThunk));
  uint8_t *calls[sizeof(kCalls) / sizeof(kCalls[0])];
  for (size_t i = 0; i < sizeof(kCalls) / sizeof(kCalls[0]); i++)
    calls[i] = FindUniqueInBank(kCalls[i], sizeof(kCalls[i]), rom, 2);
  int applied = 1;
  for (size_t i = 0; i < sizeof(kCalls) / sizeof(kCalls[0]); i++) {
    if (!calls[i]) {
      if (verbose)
        fprintf(stderr, "seed rom: skip map16 stripe call %zu (signature not unique)\n", i);
      continue;
    }
    uint8_t *op = calls[i] + 16;
    op[0] = 0x20;
    op[1] = (uint8_t)addr;
    op[2] = (uint8_t)(addr >> 8);
    applied++;
  }
  if (verbose)
    fprintf(stderr, "seed rom: map16 stripe thunk at %04X, %d of 5 sites applied\n", addr, applied);
  return applied;
}

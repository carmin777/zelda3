#include "game_over_text.h"

// US defaults. The tables are registered in game_tables.def so a mod can
// replace them through table_overrides. tools/modkit.py imports the layout
// from a translated ROM by decoding its 65816 game-over routines.
uint8 kGameOverTextLetterCount[1] = {8};

// US Tab1 at SNES $88F4EE. The two trailing entries are unused with 8 letters.
uint8 kGameOverTextTab1[kGameOverTextMaxLetters] = {
  0x40, 0x50, 0x60, 0x70, 0x88, 0x98, 0xa8, 0x40, 0x00, 0x00,
};

// US Tab2 at SNES $88F565.
uint8 kGameOverTextTab2[kGameOverTextMaxLetters] = {
  0x58, 0x60, 0x68, 0x70, 0x88, 0x90, 0x98, 0xa0, 0x00, 0x00,
};

// US character table at SNES $88F5B4, expanded to tile/attribute pairs. The
// US code hardcodes attribute $3C for both halves.
uint8 kGameOverTextTiles[kGameOverTextMaxLetters * 4] = {
  0x40, 0x3c, 0x50, 0x3c,
  0x41, 0x3c, 0x51, 0x3c,
  0x42, 0x3c, 0x52, 0x3c,
  0x43, 0x3c, 0x53, 0x3c,
  0x44, 0x3c, 0x54, 0x3c,
  0x45, 0x3c, 0x55, 0x3c,
  0x43, 0x3c, 0x53, 0x3c,
  0x46, 0x3c, 0x56, 0x3c,
  0x00, 0x00, 0x00, 0x00,
  0x00, 0x00, 0x00, 0x00,
};

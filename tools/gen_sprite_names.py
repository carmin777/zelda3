#!/usr/bin/env python3
"""Generate src/mod/sprite_names.c and .h from assets/tables.py.

The Python table (kSpriteNames) is the same one used by the extraction tools
and modkit, so mod authors see exactly the names already present in room YAML
files. Only the first 243 entries exist in kSpriteActiveRoutines.

Run this after changing assets/tables.py:

    make sprite-names
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "assets"))

import tables  # noqa: E402

COUNT = 243


def c_string(value):
  return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
  names = list(tables.kSpriteNames)
  if len(names) < COUNT:
    sys.exit("assets/tables.py has %d sprite names, need at least %d" %
             (len(names), COUNT))
  names = names[:COUNT]
  out_dir = ROOT / "src" / "mod"
  header = """// Generated by tools/gen_sprite_names.py from assets/tables.py.
// Do not edit by hand; run `make sprite-names` instead.
#ifndef ZELDA3_MOD_SPRITE_NAMES_H_
#define ZELDA3_MOD_SPRITE_NAMES_H_

#define kModSpriteTypeCount %d

// Name of each sprite type, indexed by the byte in sprite_type[]. The names
// come from assets/tables.py:kSpriteNames and are used by the Lua override
// keys (for example "Sprite:4B-Knight").
extern const char *const kModSpriteNames[kModSpriteTypeCount];

#endif  // ZELDA3_MOD_SPRITE_NAMES_H_
""" % COUNT
  lines = [
    "// Generated by tools/gen_sprite_names.py from assets/tables.py.",
    "// Do not edit by hand; run `make sprite-names` instead.",
    '#include "sprite_names.h"',
    "",
    "const char *const kModSpriteNames[kModSpriteTypeCount] = {",
  ]
  for name in names:
    lines.append("  %s," % c_string(name))
  lines.append("};")
  lines.append("")
  (out_dir / "sprite_names.h").write_text(header, encoding="utf8", newline="\n")
  (out_dir / "sprite_names.c").write_text("\n".join(lines), encoding="utf8",
                                          newline="\n")
  print("wrote src/mod/sprite_names.c and .h (%d names)" % len(names))


if __name__ == "__main__":
  main()

#!/usr/bin/env python3
"""Generate src/mod/asset_names.c from src/assets.h.

assets.h is produced by assets/compile_resources.py (--print-assets-header),
so this script is the bridge from that generated header to the asset-name
lookup used by the mod loader. Re-run it after assets.h changes:

    tools/gen_asset_names.py
"""

import argparse
import os
import re
import sys


POINTER_RE = re.compile(r'^#define\s+(k[A-Za-z0-9_]+)\s+\(\([^)]*\)g_asset_ptrs\[(\d+)\]\)')
PACKED_RE = re.compile(r'^#define\s+(k[A-Za-z0-9_]+)\(idx\)\s+FindInAssetArray\((\d+),\s*idx\)')


def parse_assets_header(path):
    names = {}
    with open(path, 'r', encoding='utf-8') as f:
        for line in f:
            line = line.strip()
            m = POINTER_RE.match(line)
            if m:
                names[int(m.group(2))] = m.group(1)
                continue
            m = PACKED_RE.match(line)
            if m:
                names[int(m.group(2))] = m.group(1)
                continue
    if not names:
        sys.exit('%s: no asset definitions found' % path)
    expected = list(range(len(names)))
    if sorted(names) != expected:
        sys.exit('%s: asset indexes are not contiguous (0..%d)' % (path, len(names) - 1))
    return [names[i] for i in expected]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', nargs='?', default='src/assets.h')
    parser.add_argument('output', nargs='?', default='src/mod/asset_names.c')
    args = parser.parse_args()

    names = parse_assets_header(args.header)
    lines = [
        '// Generated by tools/gen_asset_names.py from %s.' % args.header,
        '// Do not edit by hand; rerun the generator instead.',
        '#include "asset_names.h"',
        '#include <string.h>',
        '',
        'const char *const kAssetNames[kNumberOfAssets] = {',
    ]
    for name in names:
        lines.append('  "%s",' % name)
    lines += [
        '};',
        '',
        'int FindAssetByName(const char *name) {',
        '  for (int i = 0; i < kNumberOfAssets; i++) {',
        '    if (!strcmp(name, kAssetNames[i]))',
        '      return i;',
        '  }',
        '  return -1;',
        '}',
        '',
    ]

    os.makedirs(os.path.dirname(args.output) or '.', exist_ok=True)
    with open(args.output, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines))
    print('wrote %s with %d asset names' % (args.output, len(names)))


if __name__ == '__main__':
    main()

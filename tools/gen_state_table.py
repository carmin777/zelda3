#!/usr/bin/env python3
"""Generate src/mod/state_table.c and .h from src/variables.h.

Each simple variable in variables.h is either a scalar or an array:

    #define name (*(uint8*)(g_ram+0xNN))    scalar, 1 byte
    #define name (*(uint16*)(g_ram+0xNN))   scalar, 2 bytes
    #define name ((uint8*)(g_ram+0xNN))     array of bytes
    #define name ((uint16*)(g_ram+0xNN))    array of words

The table only describes the existing g_ram layout; variables.h itself is not
changed. Arrays do not carry a size in the header, so count is an estimate:
the distance to the next g_ram offset defined in the file divided by the
element size, clamped to 1..256. Re-run this script after variables.h changes:

    make state-table
"""

import argparse
import os
import re
import sys


DEFINE_RE = re.compile(r'^#define\s+([A-Za-z_]\w*)\s+(.+?)\s*$')
SCALAR_RE = re.compile(
    r'^\(\*\s*\(uint(?P<size>8|16)\s*\*\)\s*\(\s*g_ram\s*\+\s*'
    r'(?P<offset>0x[0-9A-Fa-f]+|[0-9]+)\s*\)\)$')
ARRAY_RE = re.compile(
    r'^\(\s*\(uint(?P<size>8|16)\s*\*\)\s*\(\s*g_ram\s*\+\s*'
    r'(?P<offset>0x[0-9A-Fa-f]+|[0-9]+)\s*\)\)$')
OFFSET_RE = re.compile(
    r'g_ram\s*\+\s*(?P<plus>0x[0-9A-Fa-f]+|[0-9]+)|'
    r'&\s*g_ram\s*\[\s*(?P<bracket>0x[0-9A-Fa-f]+|[0-9]+)\s*\]')


def parse_int(text):
    return int(text, 16) if text.lower().startswith('0x') else int(text, 10)


def parse_variables(path):
    entries = {}
    order = []
    boundaries = set()
    ignored = []

    with open(path, 'r', encoding='utf-8') as f:
        for line_number, raw_line in enumerate(f, 1):
            line = raw_line.strip()
            if not line.startswith('#define'):
                continue
            match = DEFINE_RE.match(line)
            if match is None:
                ignored.append((line_number, line))
                continue
            name, body = match.group(1), match.group(2).strip()

            offset_match = OFFSET_RE.search(body)
            if offset_match is not None:
                offset_text = offset_match.group('plus') or offset_match.group('bracket')
                boundaries.add(parse_int(offset_text))

            scalar = SCALAR_RE.match(body)
            array = ARRAY_RE.match(body)
            if scalar is None and array is None:
                # Include guards, sram-only variables and struct-typed views
                # have no simple byte/word representation in this table.
                ignored.append((line_number, line))
                continue

            is_array = array is not None
            fields = array if is_array else scalar
            elem_size = int(fields.group('size')) // 8
            offset = parse_int(fields.group('offset'))
            entry = (name, offset, elem_size, is_array)

            previous = entries.get(name)
            if previous is not None:
                if previous != entry:
                    sys.exit('%s:%d: conflicting definition for %s' %
                             (path, line_number, name))
                continue
            entries[name] = entry
            order.append(name)

    if not entries:
        sys.exit('%s: no state variables found' % path)
    return entries, boundaries, ignored


def estimate_count(offset, elem_size, boundaries):
    next_offsets = [boundary for boundary in boundaries if boundary > offset]
    limit = min(next_offsets) if next_offsets else 0x20000
    count = (limit - offset) // elem_size
    return max(1, min(256, count))


def c_string(text):
    return '"%s"' % text.replace('\\', '\\\\').replace('"', '\\"')


def generate(entries, boundaries, ignored, source_header, header_path, output_path):
    rows = []
    kinds = {'scalar8': 0, 'scalar16': 0, 'array8': 0, 'array16': 0}
    for name in sorted(entries):
        _, offset, elem_size, is_array = entries[name]
        count = estimate_count(offset, elem_size, boundaries) if is_array else 1
        rows.append((name, offset, elem_size, count, is_array))
        if is_array:
            kinds['array%d' % (elem_size * 8)] += 1
        else:
            kinds['scalar%d' % (elem_size * 8)] += 1

    header = [
        '// Generated by tools/gen_state_table.py from src/variables.h.',
        '// Do not edit by hand; run `make state-table` instead.',
        '#ifndef ZELDA3_MOD_STATE_TABLE_H_',
        '#define ZELDA3_MOD_STATE_TABLE_H_',
        '',
        '#include "../types.h"',
        '',
        '// One named variable from src/variables.h. Arrays are pointer macros',
        '// without a declared length; count is the estimate documented in the',
        '// generator (distance to the next g_ram offset, capped at 256).',
        'typedef struct StateVar {',
        '  const char *name;',
        '  uint32 offset;',
        '  uint8 elem_size;',
        '  uint16 count;',
        '  bool is_array;',
        '} StateVar;',
        '',
        'extern const StateVar kStateVars[];',
        'extern const unsigned kStateVarCount;',
        '',
        '// Binary search by exact name. Returns NULL when the name is unknown.',
        'const StateVar *StateTable_Find(const char *name);',
        '',
        '#endif  // ZELDA3_MOD_STATE_TABLE_H_',
        '',
    ]

    source = [
        '// Generated by tools/gen_state_table.py from src/variables.h.',
        '// Do not edit by hand; run `make state-table` instead.',
        '#include "state_table.h"',
        '#include <string.h>',
        '',
        'const StateVar kStateVars[] = {',
    ]
    for name, offset, elem_size, count, is_array in rows:
        source.append('  { %s, 0x%05X, %d, %d, %s },' %
                      (c_string(name), offset, elem_size, count,
                       'true' if is_array else 'false'))
    source += [
        '};',
        '',
        'const unsigned kStateVarCount = %d;' % len(rows),
        '',
        'const StateVar *StateTable_Find(const char *name) {',
        '  int lo = 0;',
        '  int hi = (int)kStateVarCount - 1;',
        '  while (lo <= hi) {',
        '    int mid = lo + (hi - lo) / 2;',
        '    int cmp = strcmp(name, kStateVars[mid].name);',
        '    if (cmp == 0)',
        '      return &kStateVars[mid];',
        '    if (cmp < 0)',
        '      hi = mid - 1;',
        '    else',
        '      lo = mid + 1;',
        '  }',
        '  return NULL;',
        '}',
        '',
    ]

    for path, lines in ((header_path, header), (output_path, source)):
        os.makedirs(os.path.dirname(path) or '.', exist_ok=True)
        with open(path, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(lines))

    print('wrote %s and %s with %d state variables' %
          (header_path, output_path, len(rows)))
    print('  scalars: %d u8, %d u16' % (kinds['scalar8'], kinds['scalar16']))
    print('  arrays:  %d u8, %d u16' % (kinds['array8'], kinds['array16']))

    if ignored:
        print('  ignored definitions: %d' % len(ignored))
        for line_number, line in ignored:
            print('    %s:%d: %s' % (os.path.basename(source_header),
                                     line_number, line))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('header', nargs='?', default='src/variables.h')
    parser.add_argument('output', nargs='?', default='src/mod/state_table.c')
    args = parser.parse_args()

    header_path = args.output[:-2] + '.h' if args.output.endswith('.c') else args.output + '.h'
    entries, boundaries, ignored = parse_variables(args.header)
    generate(entries, boundaries, ignored, args.header, header_path, args.output)


if __name__ == '__main__':
    main()
